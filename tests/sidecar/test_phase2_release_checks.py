def test_release_workflow_missing_preload_build_is_rejected(tmp_path) -> None:
    """A workflow that packages without building the gitignored preload fails.

    Regression for the release blocker: both workflows invoked electron-builder
    directly, so a clean-checkout tag build shipped an asar with no preload and
    a window whose ``jennyShell`` bridge was undefined -- while the build itself
    reported success and published.
    """
    module = _load_script_module("scripts/checks/check_release_version_policy.py")
    _write_release_policy_fixture(tmp_path)
    _write_release_workflows(tmp_path, build_preload=False)

    violations = module.validate_release_version_policy(tmp_path)

    offenders = [v for v in violations if "electron-builder" in v]
    assert len(offenders) == 2, violations
    assert all("build:preload" in violation for violation in offenders)


