def test_release_manifest_block_builds_release_body_block(tmp_path) -> None:
    module = _load_script_module("scripts/checks/release_manifest_block.py")
    asset = tmp_path / "dist" / "Jenny.exe"
    _write(asset, "installer bytes")

    block = module.build_manifest_block([asset], root=tmp_path)

    digest = hashlib.sha256(b"installer bytes").hexdigest()
    assert "| dist/Jenny.exe |" in block
    assert digest in block
    assert module.validate_manifest_block(
        block,
        require_assets=True,
        root=tmp_path,
        verify_assets=True,
    ) == []


def test_release_manifest_block_rejects_duplicate_and_misordered_markers() -> None:
    module = _load_script_module("scripts/checks/release_manifest_block.py")
    digest = "a" * 64
    block = (
        f"{module.MANIFEST_START}\n"
        "| File | SHA256 |\n"
        "| --- | --- |\n"
        f"| dist/Jenny.exe | {digest} |\n"
        f"{module.MANIFEST_END}\n"
    )

    assert module.validate_manifest_block(block + block, require_assets=True) == [
        "SHA256 manifest block must contain exactly one start marker and one end marker"
    ]
    assert module.validate_manifest_block(
        f"{module.MANIFEST_END}\n{module.MANIFEST_START}\n"
    ) == ["SHA256 manifest block markers are misordered"]
    with pytest.raises(ValueError, match="exactly one start marker"):
        module.replace_manifest_block(block + block, block)


def test_release_manifest_block_check_detects_stale_asset_hash(tmp_path) -> None:
    module = _load_script_module("scripts/checks/check_release_manifest_block.py")
    asset = tmp_path / "dist" / "Jenny.exe"
