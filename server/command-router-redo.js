'use strict';

const { hostFailure } = require('./api-contract');
const { createRateLimiter } = require('./team/rate-limit');
const { memberAuthor } = require('../services/backend/message-author');

/**
 * Row 175 item 6 (D7), F13 (D8) and F18: five team host operations on a project conversation, moved out of
 * command-router.js like the control and decision handlers. Each names its project (`project_id`, the registry row's
 * resource, so the one authorization function decides on every call and the single-owner host has none of them) and
 * the conversation (`session_id`), which must be in that project or reads as not existing (`team_not_found`). Every
 * check runs again inside the conversation's queue and after each await.
 *
 * - `team.project.regenerate` / `team.project.edit_resend` { message_id[, prompt] }: `message_id` must be the latest
 *   prompt (`team_turn_not_latest`), regenerated by its author or a project admin (`project.write`) and edited by its
 *   author only (the prompt row keeps its author, so another member's words are never put under it; any other
 *   writer `team_redo_forbidden`) while no turn runs or waits there (`session_active`). The caller keeps their lease or takes
 *   the free one, as a send does (another holder: `control_lease_unavailable`, retryable), and the backend's
 *   edit-and-regenerate runs on that prompt with the conversation's own options. The session store has no
 *   earlier-version mechanism, so as with the local chat's regenerate and edit the replaced answer is not kept; the
 *   prompt row keeps its author. Answers { session_id, stream_id?, revision, control_generation } (the lease's, to hold
 *   and release the seat the redo just took).
 * - `team.project.branch` { message_id }: a new conversation of the same project holding the messages up to and
 *   including that one (services/backend/session-branching.js, as the local branch), titled "Branch of <title>".
 *   Answers { session_id, revision }.
 * - `team.project.ask` { member_id, approval_id? }: one `teammate_asked` event to the asked member's devices only (a
 *   member of the project with at least read, not the caller: `team_member_unavailable` otherwise); no message and no
 *   turn. 6 a minute per asker, refusals included (`team_rate_limit`). An approval id must wait in this conversation
 *   (`decision_stale`). Answers {}.
 * - `team.project.hand_driver` { member_id }: the lease holder hands it to another member who may write here and is
 *   viewing it, on the device and client that last read it (`team_hand_refused` otherwise); `control_changed` names
 *   them and their client takes the lease up with `control.acquire`. Answers { member_id }.
 *
 * Answers and events carry ids only: never a prompt, a title or a name.
 */
const ASK_LIMIT = Object.freeze({ limit: 6, windowMs: 60_000, maxKeys: 64 });
// The (conversation, device) pairs whose client last read a conversation: eight members, three devices, a few each.
const MAX_SEATS = 512;
const MAX_SESSIONS = 10_000;
const TITLE_CHARS = 80;
const ANCHOR_REFUSALS = new Set(['application_turn_retry_refused', 'handoff_preparation_retry_refused']);
const STREAM_ID = /^[A-Za-z0-9_-]{1,128}$/u;
const BRANCH_KEPT = Object.freeze(['team_tool_switches', 'allowed_nodes', 'plan_mode']);

function clip(value, max) {
  const chars = Array.from(value);
  return chars.length > max ? chars.slice(0, max).join('') : value;
}

function createRedoHandlers({
  backend, leases, identity, allows, authorize, receipts, runReceipt, queue, approvals, teamCommands, trustedAuthor,
  publish, bumpRevision, chatOptions, sessionBusy, canAdmit,
}) {
  const askLimiter = createRateLimiter(ASK_LIMIT);
  const seats = new Map(); // `${session}\n${device}` -> { sessionId, deviceId, clientId, memberId }, last read last

  const projectOf = (sessionId) => {
    try { return approvals?.projectOf?.(sessionId) ?? backend.sessionStore?.peekSessionSummary?.(sessionId)?.project_id ?? null; }
    catch { return null; }
  };
  const indeterminate = (command) => hostFailure('conflict', 'operation_indeterminate', command.request_id, true);

  // The router's check again, plus the conversation's project: null when the caller may go on.
  function gate(command, context) {
    const refused = identity(command, context);
    if (refused) return refused;
    return projectOf(command.params.session_id) === command.params.project_id ? null
      : hostFailure('forbidden', 'team_not_found', command.request_id);
  }

  // A read of the conversation by a member's client (its snapshot, a viewing heartbeat that held).
  function noteViewer(sessionId, context, clientId) {
    const memberId = trustedAuthor(context)?.member_id;
    if (typeof memberId !== 'string' || typeof context?.deviceId !== 'string' || typeof clientId !== 'string') return;
    const key = `${sessionId}\n${context.deviceId}`;
    seats.delete(key);
    seats.set(key, { sessionId, deviceId: context.deviceId, clientId, memberId });
    while (seats.size > MAX_SEATS) seats.delete(seats.keys().next().value);
  }

  function publishLease(sessionId, lease) {
    publish('control_changed', { session_id: sessionId, client_id: lease.client_id, member_id: lease.member_id,
      generation: lease.generation, expires_at: lease.expires_at });
  }

  function latestPrompt(sessionId) {
    let messages;
    try { messages = backend.sessionStore?.peekSessionMessages?.(sessionId); } catch { messages = null; }
    return Array.isArray(messages) ? messages.findLast((row) => row?.role === 'user' && !row.kind) ?? null : null;
  }

  function waits(sessionId) {
    for (const map of [backend.pendingToolApprovals, backend.pendingUserQuestions]) {
      if (typeof map?.values !== 'function') continue;
      for (const entry of map.values()) if (entry?.sessionId === sessionId) return true;
    }
    return false;
  }

  // D7: the prompt's author; for a regenerate also a project admin through the same function (`project.write`).
  function mayRedo(command, context, anchor, memberId) {
    if (memberAuthor(anchor.author?.member_id)?.member_id === memberId) return true;
    if (command.operation === 'team.project.edit_resend') return false;
    return allows(command, context, 'project.write', { kind: 'project', id: command.params.project_id });
  }

  // { failure } or { anchor, memberId }: everything a redo checks before it runs, and again inside the queue.
  function redoAdmission(command, context) {
    const refused = gate(command, context);
    if (refused) return { failure: refused };
    const { session_id: sessionId, message_id: messageId } = command.params;
    const anchor = latestPrompt(sessionId);
    if (!anchor || anchor.id !== messageId || typeof anchor.content !== 'string') {
      return { failure: hostFailure('conflict', 'team_turn_not_latest', command.request_id) };
    }
    // The backend's restart would replace the prompt's attachments with none: such a turn is not redone (branch it).
    if (Array.isArray(anchor.attachments) && anchor.attachments.length) {
      return { failure: hostFailure('conflict', 'team_redo_attachments', command.request_id) };
    }
    const memberId = trustedAuthor(context)?.member_id;
    if (!memberId || !mayRedo(command, context, anchor, memberId)) {
      return { failure: hostFailure('forbidden', 'team_redo_forbidden', command.request_id) };
    }
    if (sessionBusy(sessionId) || waits(sessionId)) return { failure: hostFailure('conflict', 'session_active', command.request_id) };
    return { anchor, memberId };
  }

  // The caller keeps their lease or takes the free one, as a send's controller does: { lease }, or { failure }.
  function takeSeat(command, context, memberId) {
    const sessionId = command.params.session_id;
    const current = leases.get(sessionId);
    const theirs = current && current.client_id === command.client_id && current.device_id === context.deviceId;
    const lease = current && !theirs ? null : leases.acquire(sessionId, command.client_id, context.deviceId, false, memberId);
    if (!lease) return { failure: hostFailure('conflict', 'control_lease_unavailable', command.request_id, true) };
    if (!current) publishLease(sessionId, lease);
    return { lease };
  }

  function startOptions(command, anchor) {
    const options = chatOptions({ session_id: command.params.session_id });
    const prompt = command.operation === 'team.project.edit_resend' ? command.params.prompt : anchor.content;
    return { sessionId: command.params.session_id, editedMessageId: anchor.id, prompt, visiblePrompt: prompt,
      preferredModel: options.preferredModel, reasoningEffort: options.reasoningEffort, planMode: options.planMode,
      contextPreferences: options.contextPreferences, toolPreferences: options.toolPreferences,
      approvalMode: options.approvalMode };
  }

  function startRefusal(error, requestId) {
    const code = typeof error?.code === 'string' ? error.code : '';
    return ANCHOR_REFUSALS.has(code) ? hostFailure('conflict', code, requestId)
      : hostFailure('unavailable', 'runtime_submission_refused', requestId, true);
  }

  async function redo(command, context) {
    const early = redoAdmission(command, context);
    if (early.failure) return early.failure;
    if (!canAdmit()) return hostFailure('unavailable', 'disk_pressure', command.request_id, true);
    if (typeof backend.editAndRegenerate !== 'function') return hostFailure('unavailable', 'runtime_unavailable', command.request_id);
    const sessionId = command.params.session_id;
    return runReceipt(command, context, () => queue.run(sessionId, async () => {
      const admitted = redoAdmission(command, context);
      if (admitted.failure) return admitted.failure;
      const seat = takeSeat(command, context, admitted.memberId);
      if (seat.failure) return seat.failure;
      let started;
      try { started = await backend.editAndRegenerate(startOptions(command, admitted.anchor)); }
      catch (error) { return startRefusal(error, command.request_id); }
      const revision = bumpRevision(sessionId);
      if (gate(command, context)) return indeterminate(command);
      publish('session_changed', { session_id: sessionId, revision, reason: 'chat_saved' });
      const streamId = started?.streamId ?? started?.stream_id;
      // The lease's generation rides on the answer, so the client holds and releases the seat it was just given.
      return { ok: true, session_id: sessionId, ...(typeof streamId === 'string' && STREAM_ID.test(streamId)
        ? { stream_id: streamId } : {}), revision, control_generation: seat.lease.generation };
    }));
  }

  async function forkAt(command) {
    const { session_id: sessionId, message_id: messageId } = command.params;
    const record = backend.sessionStore?.getSession?.(sessionId) ?? {};
    const source = String(record.title || 'Chat').trim();
    // The branch keeps what limits its turns: the tool switches, the allowed nodes and Plan mode (review finding).
    const sessionFields = Object.fromEntries(BRANCH_KEPT.filter((key) => record[key] !== undefined).map((key) => [key, record[key]]));
    const { forkSessionWithArtifacts } = require('../services/backend/session-branching');
    const summary = await forkSessionWithArtifacts(backend.sessionStore, sessionId, messageId,
      { title: clip(`Branch of ${source}`, TITLE_CHARS), shadowStore: backend.shadowStore, artifactService: backend.artifactService,
        sessionFields });
    const branchId = summary?.id ?? summary?.session_id;
    return typeof branchId === 'string' && branchId ? branchId : null;
  }

  async function branch(command, context) {
    const refused = gate(command, context);
    if (refused) return refused;
    if (!canAdmit()) return hostFailure('unavailable', 'disk_pressure', command.request_id, true);
    return runReceipt(command, context, () => queue.run(command.params.session_id, async () => {
      const again = gate(command, context);
      if (again) return again;
      const ids = backend.sessionStore?.getSessionIds?.();
      if (!Array.isArray(ids) || ids.length >= MAX_SESSIONS) return hostFailure('limit', 'session_capacity', command.request_id);
      const branchId = await forkAt(command);
      if (!branchId) return hostFailure('conflict', 'team_branch_refused', command.request_id);
      const revision = bumpRevision(branchId);
      publish('session_changed', { session_id: branchId, revision, reason: 'created' });
      return gate(command, context) ? indeterminate(command) : { ok: true, session_id: branchId, revision };
    }));
  }

  function ask(command, context) {
    const refused = gate(command, context);
    if (refused) return refused;
    const asker = trustedAuthor(context)?.member_id;
    if (!asker || !askLimiter.take(asker)) return hostFailure('limit', 'team_rate_limit', command.request_id);
    const { session_id: sessionId, project_id: projectId, member_id: asked, approval_id: approvalId } = command.params;
    if (asked === asker || !teamCommands?.projectRoleOf?.(asked, projectId)) {
      return hostFailure('forbidden', 'team_member_unavailable', command.request_id);
    }
    if (approvalId !== undefined && backend.pendingToolApprovals?.get?.(approvalId)?.sessionId !== sessionId) {
      return hostFailure('conflict', 'decision_stale', command.request_id);
    }
    publish('teammate_asked', { session_id: sessionId, project_id: projectId, asker_member_id: asker, asked_member_id: asked,
      ...(approvalId !== undefined ? { approval_id: approvalId } : {}) },
    { audience: new Set([asked]), bucket: `project:${projectId}` });
    return { ok: true };
  }

  // The member's device and client that last read the conversation, still viewing it and allowed to write there.
  function seatOf(sessionId, memberId) {
    let found = null;
    for (const seat of seats.values()) {
      if (seat.sessionId !== sessionId || seat.memberId !== memberId) continue;
      if (approvals?.viewers?.isViewing(sessionId, seat.deviceId) !== true) continue;
      let verdict;
      try { verdict = authorize({ device_id: seat.deviceId }, 'session.write', { kind: 'session', id: sessionId }); } catch { verdict = null; }
      if (verdict?.ok === true) found = seat;
    }
    return found;
  }

  function hand(command, context) {
    const refused = gate(command, context);
    if (refused) return refused;
    const sessionId = command.params.session_id;
    return runReceipt(command, context, () => queue.run(sessionId, async () => {
      const again = gate(command, context);
      if (again) return again;
      const current = leases.get(sessionId);
      if (!current || current.client_id !== command.client_id || current.device_id !== context.deviceId) {
        return hostFailure('forbidden', 'control_lease_required', command.request_id);
      }
      const seat = seatOf(sessionId, command.params.member_id);
      if (!seat || seat.memberId === current.member_id) return hostFailure('forbidden', 'team_hand_refused', command.request_id);
      const lease = leases.acquire(sessionId, seat.clientId, seat.deviceId, true, seat.memberId);
      if (!lease) return hostFailure('conflict', 'control_lease_unavailable', command.request_id, true);
      publishLease(sessionId, lease);
      return { ok: true, member_id: seat.memberId };
    }));
  }

  const HANDLERS = Object.freeze({ 'team.project.regenerate': redo, 'team.project.edit_resend': redo,
    'team.project.branch': branch, 'team.project.ask': ask, 'team.project.hand_driver': hand });

  async function dispatch(command, context) {
    // A committed exact retry answers its receipt; an ask keeps none (it changes nothing).
    if (command.operation !== 'team.project.ask') {
      const previous = receipts.lookup(command, context.deviceId);
      if (previous.found) return previous.result;
    }
    return HANDLERS[command.operation](command, context);
  }

  return Object.freeze({ handles: (operation) => Object.hasOwn(HANDLERS, operation), dispatch, noteViewer });
}

module.exports = { createRedoHandlers };
