'use strict';

// Bundle preload.js and its local dependencies into one self-contained CommonJS
// file. Sandboxed Electron preloads cannot resolve arbitrary on-disk local
// requires, so only the Electron builtin remains external at runtime.

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const STAMP_BASENAME = '.preload-build-stamp.json';
const MAX_STAMP_INPUTS = 5000;
let lastBuildSkipped = false;

// Every preload entry, bundled in ONE esbuild invocation: each buildSync call
// spawns its own esbuild process, and serial spawns sat on the critical
// path of every dev launch (start.js rebuilds on boot). entryNames maps
// preload.js -> preload.bundle.js, uninstall-preload.js ->
// uninstall-preload.bundle.js. No `splitting` (cjs), so each output stays
// self-contained.
const PRELOAD_ENTRY_BASENAMES = [
  'preload.js',
  'uninstall-preload.js',
];

function computeStamp(root, inputs, esbuildVersion, buildOptions) {
  const hash = crypto.createHash('sha256');
  hash.update(JSON.stringify({ esbuildVersion, buildOptions }));
  for (const input of inputs) {
    hash.update(`\0${input.replaceAll('\\', '/')}\0`);
    hash.update(fs.readFileSync(path.resolve(root, input)));
  }
  return hash.digest('hex');
}

function fingerprintFile(filePath) {
  const stat = fs.statSync(filePath);
  const sha256 = crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex');
  return { size: stat.size, sha256 };
}

// A stamped input path round-trips through disk, so treat it as untrusted:
// reject any entry that resolves outside root (e.g. `../../../x`) instead of
// reading it.
function isPathWithinRoot(root, relativePath) {
  const relativeToRoot = path.relative(root, path.resolve(root, relativePath));
  return relativeToRoot === '' || (!relativeToRoot.startsWith('..') && !path.isAbsolute(relativeToRoot));
}

function readStamp(stampPath, root) {
  try {
    const stamp = JSON.parse(fs.readFileSync(stampPath, 'utf8'));
    const inputsValid = Array.isArray(stamp?.inputs)
      && stamp.inputs.length <= MAX_STAMP_INPUTS
      && stamp.inputs.every((input) => typeof input === 'string' && input && isPathWithinRoot(root, input));
    const outputsValid = Array.isArray(stamp?.outputs)
      && stamp.outputs.every((output) => output
        && typeof output.path === 'string' && output.path
        && typeof output.size === 'number'
        && typeof output.sha256 === 'string' && output.sha256);
    return stamp?.format === 2 && typeof stamp.value === 'string' && inputsValid && outputsValid
      ? stamp
      : null;
  } catch {
    return null;
  }
}

// The skip path used to check mere existence, so a truncated/corrupted output
// (still on disk, sources still matching the stamp's input hash) passed
// silently. Recompute each output's size+sha256 and compare against what the
// stamp recorded when it was written.
function outputsMatchStamp(root, outputs, recordedOutputs) {
  if (!Array.isArray(recordedOutputs) || recordedOutputs.length !== outputs.length) {
    return false;
  }
  return outputs.every((output, index) => {
    const recorded = recordedOutputs[index];
    if (!recorded || recorded.path !== path.relative(root, output)) return false;
    try {
      const actual = fingerprintFile(output);
      return actual.size === recorded.size && actual.sha256 === recorded.sha256;
    } catch {
      return false;
    }
  });
}

function preloadBuildPlan(root) {
  const resolvedRoot = path.resolve(root);
  const buildOptions = {
    absWorkingDir: resolvedRoot,
    entryPoints: PRELOAD_ENTRY_BASENAMES,
    outdir: resolvedRoot,
    entryNames: '[name].bundle',
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node22',
    external: ['electron'],
    minify: true,
    legalComments: 'none',
    banner: { js: '/* GENERATED by scripts/build/build-preload.js; DO NOT EDIT. */' },
    metafile: true,
  };
  const outputs = PRELOAD_ENTRY_BASENAMES.map((name) => (
    path.join(resolvedRoot, name.replace(/\.js$/, '.bundle.js'))
  ));
  return { resolvedRoot, buildOptions, outputs, stampPath: path.join(resolvedRoot, STAMP_BASENAME) };
}

// The skip test: every output still matches its recorded fingerprint and the
// recorded inputs still hash to the stamp value.
function stampIsCurrent({ resolvedRoot, buildOptions, outputs, stampPath }, esbuildVersion) {
  const previousStamp = readStamp(stampPath, resolvedRoot);
  if (!previousStamp || !outputsMatchStamp(resolvedRoot, outputs, previousStamp.outputs)) {
    return false;
  }
  try {
    return computeStamp(resolvedRoot, previousStamp.inputs, esbuildVersion, buildOptions) === previousStamp.value;
  } catch {
    // An unreadable prior input invalidates the stamp.
    return false;
  }
}

// Read-only check for an in-process launcher (main.js on unpackaged launches):
// no esbuild child process, no writes. False means a build is due.
function isPreloadBundleCurrent({ root = REPO_ROOT } = {}) {
  return stampIsCurrent(preloadBuildPlan(root), require('esbuild').version);
}

function buildPreloadBundle({ root = REPO_ROOT, env = process.env, argv = [] } = {}) {
  lastBuildSkipped = false;
  // Keep module import side-effect free for policy and contract tests. A missing
  // dev dependency becomes an actionable error only when a build is requested.
  const esbuild = require('esbuild');
  const plan = preloadBuildPlan(root);
  const { resolvedRoot, buildOptions, outputs, stampPath } = plan;
  // Packaging must never ship whatever a stale or racy stamp happened to skip,
  // so pack:release / release:windows force a rebuild. They do it with the
  // --force argv flag, not this env var: npm runs scripts through cmd.exe on
  // Windows but `sh` on macOS/Linux, and `set VAR=1 && ...` is cmd-only -- under
  // sh it sets a positional parameter and exports nothing, so the force would
  // have silently done nothing on exactly the macOS release path. The env var
  // stays for manual invocation. Trimmed because cmd.exe's
  // `set VAR=1 && next-command` leaves a trailing space IN THE VALUE.
  const forceRebuild = String(env.JENNY_PRELOAD_FORCE_REBUILD || '').trim() === '1'
    || argv.includes('--force');
  if (!forceRebuild && stampIsCurrent(plan, esbuild.version)) {
    lastBuildSkipped = true;
    return { output: outputs[0], skipped: true };
  }

  fs.rmSync(stampPath, { force: true });
  const buildStartedAt = Date.now();
  const result = esbuild.buildSync(buildOptions);
  if (!result.metafile || !result.metafile.inputs) {
    throw new Error('esbuild completed without the requested preload input metafile');
  }
  if (!outputs.every((output) => fs.existsSync(output))) {
    throw new Error('esbuild completed without writing every preload bundle');
  }
  const inputs = [...new Set([
    ...PRELOAD_ENTRY_BASENAMES,
    ...Object.keys(result.metafile.inputs),
  ])].map((input) => path.relative(resolvedRoot, path.resolve(resolvedRoot, input))).sort();

  // esbuild already read these sources inside buildSync above. A source
  // written AFTER that read but before this check is hashed into the stamp
  // below yet is NOT reflected in the bundle esbuild just emitted -- writing
  // the stamp then would make the stale-bundle skip permanent. Leave the
  // stamp absent instead so the next launch rebuilds.
  const builtDuringRace = inputs.some((input) => {
    try {
      return fs.statSync(path.resolve(resolvedRoot, input)).mtimeMs > buildStartedAt;
    } catch {
      return true;
    }
  });
  if (builtDuringRace) {
    return { output: outputs[0], skipped: false };
  }

  const value = computeStamp(resolvedRoot, inputs, esbuild.version, buildOptions);
  const outputStamps = outputs.map((output) => ({
    path: path.relative(resolvedRoot, output),
    ...fingerprintFile(output),
  }));
  fs.writeFileSync(
    stampPath,
    `${JSON.stringify({ format: 2, value, inputs, outputs: outputStamps }, null, 2)}\n`,
    'utf8',
  );
  return { output: outputs[0], skipped: false };
}

if (require.main === module) {
  const { output, skipped } = buildPreloadBundle({ argv: process.argv.slice(2) });
  process.stdout.write(
    `preload bundle ${skipped ? 'unchanged; esbuild skipped' : 'written'}: `
      + `${path.relative(REPO_ROOT, output)}\n`,
  );
}

module.exports = {
  buildPreloadBundle,
  isPreloadBundleCurrent,
  preloadBuildPlan,
  REPO_ROOT,
};
