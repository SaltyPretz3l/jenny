'use strict';

// Builds Jenny's two Sketchy bundles from the vendored drawing core (vendor/sketchy/):
//   sketch-frame.bundle.js   browser IIFE, global `jennySketch`; the sandboxed sketch frame loads it. Ships.
//   sketch-core.bundle.cjs   Node CommonJS (parse, build, layout, no DOM); tests only. Never ships.
// Both land at the repository root, are gitignored and are rebuilt only when a content stamp over their
// inputs changes (the same stamp scheme as build-preload.js). `--force` rebuilds regardless.

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const { sketchPlugin } = require('./sketch/esbuild-plugin');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const STAMP_BASENAME = '.sketch-build-stamp.json';
const MAX_STAMP_INPUTS = 5000;
const MAX_FRAME_BYTES = 3_000_000;
const FRAME_BASENAME = 'sketch-frame.bundle.js';
const CORE_BASENAME = 'sketch-core.bundle.cjs';
const GENERATED = '/* GENERATED by scripts/build/build-sketch.js from vendor/sketchy; DO NOT EDIT. */';

function sketchBuildPlan(root = REPO_ROOT) {
  const resolvedRoot = path.resolve(root);
  const sketchDir = path.join(resolvedRoot, 'scripts', 'build', 'sketch');
  return {
    resolvedRoot,
    sketchDir,
    vendorDir: path.join(resolvedRoot, 'vendor', 'sketchy'),
    elkFile: path.join(resolvedRoot, 'node_modules', 'elkjs', 'lib', 'elk.bundled.js'),
    frameOutput: path.join(resolvedRoot, FRAME_BASENAME),
    coreOutput: path.join(resolvedRoot, CORE_BASENAME),
    outputs: [path.join(resolvedRoot, FRAME_BASENAME), path.join(resolvedRoot, CORE_BASENAME)],
    stampPath: path.join(resolvedRoot, STAMP_BASENAME),
  };
}

// One options object per bundle. The frame is minified browser code that must not fetch anything;
// the core stays readable because only tests load it.
function bundleOptions(plan) {
  const common = {
    absWorkingDir: plan.resolvedRoot,
    bundle: true,
    // import.meta.url feeds upstream's createRequire call, which the node:module shim answers.
    define: { 'import.meta.url': JSON.stringify('file:///sketch-bundle') },
    // Upstream's own tsconfig is not vendored and must never be picked up.
    tsconfigRaw: { compilerOptions: { target: 'es2022', verbatimModuleSyntax: false } },
    target: 'es2022',
    legalComments: 'none',
    logLevel: 'silent',
    metafile: true,
    plugins: [sketchPlugin({ vendorDir: plan.vendorDir, sketchDir: plan.sketchDir, elkFile: plan.elkFile })],
  };
  return {
    frame: {
      ...common,
      entryPoints: [path.join(plan.sketchDir, 'entry-frame.ts')],
      outfile: plan.frameOutput,
      format: 'iife',
      globalName: 'jennySketch',
      platform: 'browser',
      minify: true,
      banner: { js: GENERATED },
    },
    core: {
      ...common,
      entryPoints: [path.join(plan.sketchDir, 'entry-core.ts')],
      outfile: plan.coreOutput,
      format: 'cjs',
      platform: 'node',
      minify: false,
      banner: { js: GENERATED },
    },
  };
}

// The stamp covers the build options (minus the plugin function), this script and every input esbuild read.
function stampDescriptor(options, esbuildVersion) {
  const describe = ({ plugins, ...rest }) => rest;
  return { esbuildVersion, frame: describe(options.frame), core: describe(options.core) };
}

function computeStamp(root, inputs, descriptor) {
  const hash = crypto.createHash('sha256');
  hash.update(JSON.stringify(descriptor));
  hash.update(fs.readFileSync(__filename));
  for (const input of inputs) {
    hash.update(`\0${input.replaceAll('\\', '/')}\0`);
    hash.update(fs.readFileSync(path.resolve(root, input)));
  }
  return hash.digest('hex');
}

function fingerprintFile(filePath) {
  const stat = fs.statSync(filePath);
  const sha256 = crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex');
  return { size: stat.size, sha256 };
}

function isPathWithinRoot(root, relativePath) {
  const relativeToRoot = path.relative(root, path.resolve(root, relativePath));
  return relativeToRoot === '' || (!relativeToRoot.startsWith('..') && !path.isAbsolute(relativeToRoot));
}

function readStamp(stampPath, root) {
  try {
    const stamp = JSON.parse(fs.readFileSync(stampPath, 'utf8'));
    const inputsValid = Array.isArray(stamp?.inputs)
      && stamp.inputs.length <= MAX_STAMP_INPUTS
      && stamp.inputs.every((input) => typeof input === 'string' && input && isPathWithinRoot(root, input));
    const outputsValid = Array.isArray(stamp?.outputs)
      && stamp.outputs.every((output) => output
        && typeof output.path === 'string' && output.path
        && typeof output.size === 'number'
        && typeof output.sha256 === 'string' && output.sha256);
    return stamp?.format === 1 && typeof stamp.value === 'string' && inputsValid && outputsValid ? stamp : null;
  } catch {
    return null;
  }
}

function outputsMatchStamp(root, outputs, recordedOutputs) {
  if (!Array.isArray(recordedOutputs) || recordedOutputs.length !== outputs.length) return false;
  return outputs.every((output, index) => {
    const recorded = recordedOutputs[index];
    if (!recorded || recorded.path !== path.relative(root, output)) return false;
    try {
      const actual = fingerprintFile(output);
      return actual.size === recorded.size && actual.sha256 === recorded.sha256;
    } catch {
      return false;
    }
  });
}

// The quick check: a digest of the build options plus the size and modified time of this script, every
// input and both outputs. When all of them equal the stamp's, nothing is read or hashed, so a dev launch
// pays a few stat calls instead of hashing about 12 MB. Any difference falls back to the content hashes,
// which stay the authority (a file rewritten with the same content is still current).
function quickKey(descriptor) {
  return crypto.createHash('sha256').update(JSON.stringify(descriptor)).digest('hex');
}

function quickStats(plan, inputs) {
  const files = [__filename, ...inputs.map((input) => path.resolve(plan.resolvedRoot, input)), ...plan.outputs];
  return files.map((file) => {
    const stat = fs.statSync(file);
    return [stat.size, stat.mtimeMs];
  });
}

function quickMatches(plan, previous, descriptor) {
  try {
    return previous.quick?.key === quickKey(descriptor)
      && JSON.stringify(previous.quick.stats) === JSON.stringify(quickStats(plan, previous.inputs));
  } catch {
    return false;
  }
}

function stampIsCurrent(plan, esbuildVersion) {
  const previous = readStamp(plan.stampPath, plan.resolvedRoot);
  if (!previous) return false;
  const descriptor = stampDescriptor(bundleOptions(plan), esbuildVersion);
  if (quickMatches(plan, previous, descriptor)) return true;
  if (!outputsMatchStamp(plan.resolvedRoot, plan.outputs, previous.outputs)) return false;
  try {
    return computeStamp(plan.resolvedRoot, previous.inputs, descriptor) === previous.value;
  } catch {
    return false;
  }
}

// Read-only check for the launcher: no esbuild run, no writes. False means a build is due.
function isSketchBundleCurrent({ root = REPO_ROOT } = {}) {
  return stampIsCurrent(sketchBuildPlan(root), require('esbuild').version);
}

// A metafile key is a path relative to the working directory, optionally prefixed by a plugin namespace.
function metafileInputs(metafile, root) {
  const found = new Set();
  for (const key of Object.keys(metafile.inputs)) {
    const file = key.replace(/^inline:/, '');
    const relative = path.relative(root, path.resolve(root, file));
    if (isPathWithinRoot(root, relative) && fs.existsSync(path.resolve(root, relative))) found.add(relative);
  }
  return [...found].sort();
}

function sizesOf(plan) {
  return plan.outputs.map((output) => ({ path: path.relative(plan.resolvedRoot, output), size: fs.statSync(output).size }));
}

async function buildSketchBundles({ root = REPO_ROOT, env = process.env, argv = [] } = {}) {
  const esbuild = require('esbuild');
  const plan = sketchBuildPlan(root);
  const forceRebuild = String(env.JENNY_SKETCH_FORCE_REBUILD || '').trim() === '1' || argv.includes('--force');
  if (!forceRebuild && stampIsCurrent(plan, esbuild.version)) {
    return { skipped: true, outputs: sizesOf(plan) };
  }

  fs.rmSync(plan.stampPath, { force: true });
  const startedAt = Date.now();
  const options = bundleOptions(plan);
  const [frame, core] = await Promise.all([esbuild.build(options.frame), esbuild.build(options.core)]);
  if (!frame.metafile?.inputs || !core.metafile?.inputs) {
    throw new Error('esbuild completed without the requested sketch input metafile');
  }
  if (!plan.outputs.every((output) => fs.existsSync(output))) {
    throw new Error('esbuild completed without writing both sketch bundles');
  }
  const frameBytes = fs.statSync(plan.frameOutput).size;
  if (frameBytes > MAX_FRAME_BYTES) {
    throw new Error(`${FRAME_BASENAME} is ${frameBytes} bytes, over the ${MAX_FRAME_BYTES} byte ceiling`);
  }

  const inputs = [...new Set([
    ...metafileInputs(frame.metafile, plan.resolvedRoot),
    ...metafileInputs(core.metafile, plan.resolvedRoot),
  ])].sort();
  // A source written after esbuild read it would be hashed into the stamp but missing from the bundle,
  // making a stale bundle skippable for good. Leave the stamp absent so the next call rebuilds.
  const builtDuringRace = inputs.some((input) => {
    try {
      return fs.statSync(path.resolve(plan.resolvedRoot, input)).mtimeMs > startedAt;
    } catch {
      return true;
    }
  });
  if (!builtDuringRace) {
    const descriptor = stampDescriptor(options, esbuild.version);
    const value = computeStamp(plan.resolvedRoot, inputs, descriptor);
    const outputStamps = plan.outputs.map((output) => ({ path: path.relative(plan.resolvedRoot, output), ...fingerprintFile(output) }));
    const quick = { key: quickKey(descriptor), stats: quickStats(plan, inputs) };
    fs.writeFileSync(plan.stampPath, `${JSON.stringify({ format: 1, value, inputs, outputs: outputStamps, quick }, null, 2)}\n`, 'utf8');
  }
  return { skipped: false, outputs: sizesOf(plan) };
}

if (require.main === module) {
  buildSketchBundles({ argv: process.argv.slice(2) }).then(({ skipped, outputs }) => {
    const sizes = outputs.map((output) => `${output.path} ${output.size} bytes`).join(', ');
    process.stdout.write(`sketch bundles ${skipped ? 'unchanged; esbuild skipped' : 'written'}: ${sizes}\n`);
  }, (error) => {
    process.stderr.write(`sketch bundle build failed: ${String((error && error.message) || error)}\n`);
    process.exitCode = 1;
  });
}

module.exports = {
  buildSketchBundles,
  isSketchBundleCurrent,
  sketchBuildPlan,
  MAX_FRAME_BYTES,
  REPO_ROOT,
};
