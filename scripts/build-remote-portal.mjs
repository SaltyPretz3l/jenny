import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDirectory, '..');
const portalDirectory = path.join(root, 'remote', 'portal');
const outputPath = path.join(root, 'remote', 'relay', 'src', 'portal-bundle.js');
const checkOnly = process.argv.slice(2).includes('--check');
const forbidden = [
  ['dynamic markup assignment', /innerHTML/],
  ['dynamic code evaluation', /eval\s*\(/],
  ['function constructor', /new\s+Function/],
  ['insecure URL', /http:\/\//],
  ['external URL', /https:\/\//],
];

function sha256Base64(value) {
  return createHash('sha256').update(value, 'utf8').digest('base64');
}

function refuseForbidden(bundle) {
  for (const [name, pattern] of forbidden) {
    if (pattern.test(bundle)) throw new Error(`Remote portal bundle contains forbidden ${name}.`);
  }
}

async function render() {
  const [template, style, built] = await Promise.all([
    readFile(path.join(portalDirectory, 'index.html'), 'utf8'),
    readFile(path.join(portalDirectory, 'portal.css'), 'utf8'),
    build({
      absWorkingDir: root,
      entryPoints: ['remote/portal/portal-entry.js'],
      bundle: true,
      format: 'iife',
      platform: 'browser',
      target: 'es2022',
      minify: false,
      legalComments: 'none',
      write: false,
    }),
  ]);
  const script = built.outputFiles[0].text.trim();
  refuseForbidden(script);
  const html = template
    .replace('<style data-portal-style></style>', `<style>${style.trim()}</style>`)
    .replace('<script data-portal-script></script>', `<script>${script}</script>`);
  refuseForbidden(html);
  if ((html.match(/<script(?:\s|>)/g) || []).length !== 1
    || (html.match(/<style(?:\s|>)/g) || []).length !== 1) {
    throw new Error('Remote portal must contain exactly one inline script and style.');
  }
  const scriptHash = sha256Base64(script);
  const styleHash = sha256Base64(style.trim());
  return [
    '// Generated by scripts/build-remote-portal.mjs. Do not edit.',
    `export const PORTAL_HTML = ${JSON.stringify(html)};`,
    `export const PORTAL_SCRIPT_SHA256 = ${JSON.stringify(scriptHash)};`,
    `export const PORTAL_STYLE_SHA256 = ${JSON.stringify(styleHash)};`,
    '',
  ].join('\n');
}

const expected = await render();
if (checkOnly) {
  let current = '';
  try { current = await readFile(outputPath, 'utf8'); } catch (_error) { /* stale below */ }
  if (current !== expected) {
    console.error('remote/relay/src/portal-bundle.js is stale; run npm run build:remote-portal.');
    process.exitCode = 1;
  } else {
    console.log('Remote portal bundle is current.');
  }
} else {
  await writeFile(outputPath, expected, 'utf8');
  console.log('Built remote/relay/src/portal-bundle.js.');
}
