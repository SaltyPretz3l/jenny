#!/usr/bin/env node
'use strict';

// The translation pass: feature commits add English strings only, and one pass
// before a public release brings every shipped language level with English.
//
//   worklist [--out <file>]            what each language owes
//   apply --tag <tag> --from <file>    merge one language's answers
//   seal                               prune, validate strictly, rebuild, record
//   check                              has English moved since the last seal?
//
// worklist and apply read the earlier English from the marker's commit;
// --base-file <en.json> supplies it when that commit is no longer reachable.
//
// The marker (translation-sync.json) records the English catalog the languages
// were last level with. A reworded English string keeps its key, so key parity
// alone cannot see it; the marker's digest can.

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { buildCatalogs, compareOrdinal, parseCatalog } = require('./build-catalogs');
const { movedFamilies, splitKey, validateCatalog } = require('./validate-catalogs');

const MARKER_RELATIVE = 'scripts/i18n/translation-sync.json';
// en is the source and qps-ploc is generated by the ledger scan.
const UNTRANSLATED_TAGS = new Set(['en', 'qps-ploc']);
const GIT_MAX_BUFFER = 64 * 1024 * 1024;

function parseArguments(argv) {
  const [command, ...rest] = argv;
  const options = { command, root: process.cwd(), out: null, baseFile: null, tag: null, from: null };
  const valueFlags = { '--root': 'root', '--out': 'out', '--base-file': 'baseFile', '--tag': 'tag', '--from': 'from' };
  for (let index = 0; index < rest.length; index += 1) {
    const name = valueFlags[rest[index]];
    if (!name) throw new Error(`unknown argument: ${rest[index]}`);
    const value = rest[index += 1];
    if (!value) throw new Error(`${rest[index - 1]} requires a value`);
    options[name] = value;
  }
  options.root = path.resolve(options.root);
  return options;
}

function readStrings(file, tag) {
  return parseCatalog(JSON.parse(fs.readFileSync(file, 'utf8')), tag);
}

function localeFile(root, tag) {
  return path.join(root, 'locales', `${tag}.json`);
}

function translatedTags(root) {
  return fs.readdirSync(path.join(root, 'locales'))
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -5))
    .filter((tag) => !UNTRANSLATED_TAGS.has(tag))
    .sort(compareOrdinal);
}

// Order-independent, so a re-sorted en.json is not a content change.
function englishDigest(strings) {
  const hash = crypto.createHash('sha256');
  for (const key of Object.keys(strings).sort(compareOrdinal)) {
    hash.update(JSON.stringify([key, strings[key]]));
    hash.update('\n');
  }
  return hash.digest('hex');
}

function readMarker(root) {
  const marker = JSON.parse(fs.readFileSync(path.join(root, MARKER_RELATIVE), 'utf8'));
  if (typeof marker.englishCommit !== 'string' || typeof marker.englishSha256 !== 'string') {
    throw new Error(`${MARKER_RELATIVE} must carry englishCommit and englishSha256`);
  }
  return marker;
}

function writeMarker(root, marker) {
  fs.writeFileSync(path.join(root, MARKER_RELATIVE), `${JSON.stringify(marker, null, 2)}\n`, 'utf8');
}

function git(root, ...args) {
  // A Buffer, decoded here: a text-mode read of a blob can mangle UTF-8.
  return execFileSync('git', args, { cwd: root, maxBuffer: GIT_MAX_BUFFER }).toString('utf8');
}

function gitEnglish(root, ref) {
  return parseCatalog(JSON.parse(git(root, 'show', `${ref}:locales/en.json`)), 'en');
}

function baseEnglishFor(options) {
  return options.baseFile
    ? readStrings(path.resolve(options.baseFile), 'en')
    : gitEnglish(options.root, readMarker(options.root).englishCommit);
}

function familyBases(strings) {
  const bases = new Map();
  for (const key of Object.keys(strings)) {
    const { base } = splitKey(key);
    if (!bases.has(base)) bases.set(base, []);
    bases.get(base).push(key);
  }
  return bases;
}

function computeWorklist(baseEnglish, english, catalogs) {
  const families = familyBases(english);
  const baseFamilies = familyBases(baseEnglish);
  const moved = movedFamilies(baseEnglish, english);
  const removed = [...baseFamilies.keys()].filter((base) => !families.has(base)).sort(compareOrdinal);

  const locales = {};
  const wanted = new Set();
  for (const tag of Object.keys(catalogs).sort(compareOrdinal)) {
    const present = familyBases(catalogs[tag]);
    const owed = [...families.keys()]
      .filter((base) => moved.has(base) || !present.has(base))
      .sort(compareOrdinal);
    const unknown = [...present.keys()].filter((base) => !families.has(base)).sort(compareOrdinal);
    owed.forEach((base) => wanted.add(base));
    locales[tag] = {
      // Sorted: the engine's own order differs between ICU versions.
      pluralCategories: [...new Intl.PluralRules(tag).resolvedOptions().pluralCategories].sort(compareOrdinal),
      families: owed,
      unknown,
    };
  }

  const englishEntries = {};
  for (const base of [...wanted].sort(compareOrdinal)) {
    for (const key of [...families.get(base)].sort(compareOrdinal)) {
      const entry = { text: english[key] };
      if (Object.prototype.hasOwnProperty.call(baseEnglish, key) && baseEnglish[key] !== english[key]) {
        entry.previous = baseEnglish[key];
      }
      englishEntries[key] = entry;
    }
  }
  return { english: englishEntries, removed, locales };
}

// Replaces whole key families (a language's plural categories differ from
// English's), drops keys English no longer has, and keeps the catalog's
// existing key order so the diff shows only what was translated.
function applyTranslations(strings, english, translations) {
  const englishFamilies = familyBases(english);
  const incoming = familyBases(translations);
  for (const base of incoming.keys()) {
    if (!englishFamilies.has(base)) throw new Error(`${base}: not an English key`);
  }
  const result = {};
  const placed = new Set();
  const place = (base) => {
    if (placed.has(base)) return;
    placed.add(base);
    for (const key of [...incoming.get(base)].sort(compareOrdinal)) result[key] = translations[key];
  };
  for (const key of Object.keys(strings)) {
    const { base } = splitKey(key);
    if (!englishFamilies.has(base)) continue;
    if (incoming.has(base)) place(base);
    else result[key] = strings[key];
  }
  for (const base of [...incoming.keys()].sort(compareOrdinal)) place(base);
  return result;
}

function writeStrings(file, strings) {
  fs.writeFileSync(file, `${JSON.stringify(strings, null, 2)}\n`, 'utf8');
}

function loadCatalogs(root) {
  const catalogs = {};
  for (const tag of translatedTags(root)) catalogs[tag] = readStrings(localeFile(root, tag), tag);
  return catalogs;
}

function runWorklist(options) {
  const english = readStrings(localeFile(options.root, 'en'), 'en');
  const worklist = {
    base: readMarker(options.root).englishCommit,
    ...computeWorklist(baseEnglishFor(options), english, loadCatalogs(options.root)),
  };
  for (const [tag, entry] of Object.entries(worklist.locales)) {
    console.log(`${tag}: ${entry.families.length} to translate, ${entry.unknown.length} to prune`);
  }
  console.log(`English keys in the worklist: ${Object.keys(worklist.english).length}; removed: ${worklist.removed.length}`);
  if (options.out) {
    fs.writeFileSync(path.resolve(options.out), `${JSON.stringify(worklist, null, 2)}\n`, 'utf8');
    console.log(`WROTE: ${path.resolve(options.out)}`);
  }
  return 0;
}

function runApply(options) {
  if (!options.tag || !options.from) throw new Error('apply requires --tag and --from');
  if (UNTRANSLATED_TAGS.has(options.tag)) throw new Error(`${options.tag} is not a translated catalog`);
  const english = readStrings(localeFile(options.root, 'en'), 'en');
  const file = localeFile(options.root, options.tag);
  const translations = parseCatalog(JSON.parse(fs.readFileSync(path.resolve(options.from), 'utf8')), options.tag);
  const next = applyTranslations(readStrings(file, options.tag), english, translations);
  // Families this answers file does not cover may still be stale; only the
  // seal requires the whole language to be level.
  const moved = movedFamilies(baseEnglishFor(options), english);
  for (const key of Object.keys(translations)) moved.delete(splitKey(key).base);
  const { failures, warnings } = validateCatalog(options.tag, next, english, { moved });
  if (failures.length) {
    for (const failure of failures) console.error(failure);
    console.error(`NOT WRITTEN: locales/${options.tag}.json`);
    return 1;
  }
  writeStrings(file, next);
  const stillMissing = warnings.filter((line) => line.endsWith(': missing English key')).length;
  console.log(`APPLIED: ${Object.keys(translations).length} key(s) to locales/${options.tag}.json; ${stillMissing} still missing`);
  return 0;
}

function runSeal(options) {
  const { root } = options;
  const english = readStrings(localeFile(root, 'en'), 'en');
  if (englishDigest(gitEnglish(root, 'HEAD')) !== englishDigest(english)) {
    throw new Error('locales/en.json differs from HEAD; commit the English change before sealing');
  }
  const failures = [];
  const prunedFiles = [];
  for (const tag of translatedTags(root)) {
    const file = localeFile(root, tag);
    const strings = readStrings(file, tag);
    const pruned = applyTranslations(strings, english, {});
    if (Object.keys(pruned).length !== Object.keys(strings).length) prunedFiles.push([file, pruned]);
    failures.push(...validateCatalog(tag, pruned, english, { strict: true }).failures);
  }
  if (failures.length) {
    for (const failure of failures) console.error(failure);
    console.error('NOT SEALED: the catalogs above still owe translations; nothing was written');
    return 1;
  }
  for (const [file, pruned] of prunedFiles) writeStrings(file, pruned);
  buildCatalogs(path.join(root, 'locales'));
  writeMarker(root, { englishCommit: git(root, 'rev-parse', 'HEAD').trim(), englishSha256: englishDigest(english) });
  console.log(`SEALED: ${MARKER_RELATIVE} records the current English catalog`);
  return 0;
}

function runCheck(options) {
  const english = readStrings(localeFile(options.root, 'en'), 'en');
  if (readMarker(options.root).englishSha256 === englishDigest(english)) {
    console.log('PASS: English is unchanged since the last translation pass');
    return 0;
  }
  console.error(
    'FAIL: locales/en.json changed since the last translation pass; run '
    + '`node scripts/i18n/translation-pass.js worklist`, translate, then `seal`'
  );
  return 1;
}

function main(argv = process.argv.slice(2)) {
  try {
    const options = parseArguments(argv);
    const commands = { worklist: runWorklist, apply: runApply, seal: runSeal, check: runCheck };
    const run = commands[options.command];
    if (!run) throw new Error('usage: translation-pass.js <worklist|apply|seal|check> [options]');
    return run(options);
  } catch (error) {
    console.error(`ERROR: ${error.message}`);
    return 1;
  }
}

if (require.main === module) process.exitCode = main();

module.exports = { applyTranslations, computeWorklist, englishDigest, main };
