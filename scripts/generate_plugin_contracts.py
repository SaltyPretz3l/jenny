# --- Closed descriptor vocabulary ------------------------------------------------

ALLOWED_TYPES = {"object", "array", "string", "integer", "boolean", "enum", "const", "ref", "tagged_union"}
ALLOWED_ADDITIONAL_PROPERTIES = {"reject", "ignore", "preserve"}
SAFE_INTEGER_MIN = -9007199254740991
SAFE_INTEGER_MAX = 9007199254740991

# Named string formats. Generation-time resolution bakes the pattern/byte cap/
# NFC-check policy directly into each resolved string node, so neither runtime
# interpreter needs a "format" lookup table at validation time.
# Patterns use explicit [0-9] rather than \d. Python's re treats \d as ALL
# Unicode decimal digits while JavaScript's RegExp (without the u flag) treats
# it as ASCII [0-9] only, so a \d here would make the two generated runtimes
# disagree -- Python accepting Arabic-Indic "٢٠٢٤-..." timestamps that JS
# rejects. _lint_pattern rejects the shorthand classes outright so this cannot
# regress. Same reasoning applies to \w, \s and \b.
FORMATS: dict[str, dict[str, Any]] = {
    "sha256_hex": {"pattern": r"^[0-9a-f]{64}$", "max_utf8_bytes": 64, "nfc_check": False},
    "iso8601_utc": {"pattern": r"^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]{1,6})?Z$", "max_utf8_bytes": 40, "nfc_check": False},
    "display_string": {"pattern": r"^[^\x00-\x1F\x7F-\x9F]+$", "max_utf8_bytes": 120, "nfc_check": True},
    "nfc_identifier": {"pattern": r"^[a-z][a-z0-9_-]{0,63}$", "max_utf8_bytes": 64, "nfc_check": True},
    "semver": {"pattern": r"^[0-9]{1,5}\.[0-9]{1,5}\.[0-9]{1,5}(-[0-9A-Za-z.-]{1,32})?(\+[0-9A-Za-z.-]{1,32})?$", "max_utf8_bytes": 80, "nfc_check": False},
    "publisher_id": {"pattern": r"^[a-z][a-z0-9-]{0,63}$", "max_utf8_bytes": 64, "nfc_check": True},
    "plugin_id": {"pattern": r"^[a-z][a-z0-9_-]{0,63}$", "max_utf8_bytes": 64, "nfc_check": True},
    "contribution_id": {"pattern": r"^[a-z][a-z0-9_-]{0,63}$", "max_utf8_bytes": 64, "nfc_check": True},
    "operation_id": {"pattern": r"^[a-z0-9][a-z0-9_-]{0,63}$", "max_utf8_bytes": 64, "nfc_check": True},
    "generation_id": {"pattern": r"^[a-z0-9][a-z0-9_-]{0,63}$", "max_utf8_bytes": 64, "nfc_check": True},
}
ALLOWED_FORMATS = set(FORMATS.keys())

