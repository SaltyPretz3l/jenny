"""Generate the cross-runtime plugin-platform contract validators.

Reads the closed-vocabulary descriptor schemas under config/plugins/v1/ through
config/plugins/v6/ plus independently versioned extension families,
lints them against the supported facet subset, resolves $defs references
and named string formats at generation time, and emits two interpreters
(JS + Python) that share one embedded SPEC and one validation algorithm so
a fix lands in both runtimes at once.

Regen: python scripts/generate_plugin_contracts.py
Check: python scripts/generate_plugin_contracts.py --check
"""

